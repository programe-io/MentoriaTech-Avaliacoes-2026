function addComment(e,index){
    e.preventDefault();
    const input=document.getElementById(`input-${index}`);
    const msg=input.value.trim();
    if(!msg) return;
    const comments=document.getElementById(`comments-${index}`);
    const div=document.createElement("div");
    div.className="comment";
    div.innerHTML=`<strong>Você:</strong> ${msg}`;
    comments.appendChild(div);
    document.getElementById(`comment-count-${index}`).textContent=comments.children.length+" comentários";
    addLog("Você comentou em "+posts[index].name);
    input.value="";
}
