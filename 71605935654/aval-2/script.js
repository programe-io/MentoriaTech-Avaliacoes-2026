/* Entrada de Dados */
let media1 = Number(prompt('Informe a 1ª média: '));
let media2 = Number(prompt('Informe a 2ª média: '));
let media3 = Number(prompt('Informe a 3ª média: '));
let media4 = Number(prompt('Informe a 4ª média: '));

/* Processamento */
let mediaFinal = (media1 + media2 + media3 + media4) / 4;

/* Saída */
console.log(`A média do aluno foi: \${mediaFinal\}`)
