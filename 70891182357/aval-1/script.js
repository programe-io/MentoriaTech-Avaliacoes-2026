let numero = 12;

switch (numero) {
    case 3:
        console.log("O valor é igual a 3");
        break;

    case 6:
        console.log("O valor é igual a 6");
        break;

    case 10:
        console.log("O valor é igual a 10");
        break;

    case 15:
        console.log("O valor é igual a 15");
        break;

    default:
        console.log("Não temos case para o valor especificado");
}