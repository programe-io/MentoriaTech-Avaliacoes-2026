let numero = 12;

switch(numero) {
    case 5:
        console.log('O valor é igual a 5');
        break;

    case 7:
        console.log('O valor é igual a 7');
        break;

    case 10:
        console.log('O valor é igual a 10');
        break;

    case 15:
        console.log('O valor é igual a 15');
        break;

    default:
        console.log("Não tenho um case para o valor especificado");
        break;
}